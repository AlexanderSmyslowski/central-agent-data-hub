def resolve_language(value: str | None) -> str:
    if value in SUPPORTED_LANGUAGES:
        return value
    return DEFAULT_LANGUAGE


def translator(language: str) -> Callable[..., str]:
    resolved = resolve_language(language)

    def translate(key: str, **kwargs: object) -> str:
        text = TRANSLATIONS.get(resolved, {}).get(
            key,
            TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key),
        )
        return text.format(**kwargs) if kwargs else text

    return translate


def pluralizer(language: str) -> Callable[..., str]:
    translate = translator(language)

    def pluralize(key: str, count: object, **kwargs: object) -> str:
        try:
            numeric_count = int(count)
        except (TypeError, ValueError):
            numeric_count = 0
        plural_key = f"{key}_one" if numeric_count == 1 else f"{key}_many"
        return translate(plural_key, count=numeric_count, **kwargs)

    return pluralize


def localize_ui_text(text: object, language: str) -> str:
    value = str(text or "")
    return KNOWN_UI_TEXT_TRANSLATIONS.get(resolve_language(language), {}).get(
        value,
        value,
    )


def with_language(url: str, language: str) -> str:
    if not url or url.startswith("#"):
        return url
    parts = urlsplit(url)
    query_pairs = parse_qsl(parts.query, keep_blank_values=True)
    resolved_language = resolve_language(language)
    if resolved_language == DEFAULT_LANGUAGE and not any(
        key == "lang" for key, _value in query_pairs
    ):
        return url
    query = [
        (key, value)
        for key, value in query_pairs
        if key != "lang"
    ]
    if resolved_language != DEFAULT_LANGUAGE:
        query.append(("lang", language))
    return urlunsplit(
        (parts.scheme, parts.netloc, parts.path, urlencode(query), parts.fragment)
    )


def language_switch_links(current_path: str, query_string: str) -> list[dict[str, object]]:
    current = f"{current_path}?{query_string}" if query_string else current_path
    links = []
    for code in SUPPORTED_LANGUAGES:
        parts = urlsplit(with_language(current, code))
        links.append(
            {
                "code": code,
                "label": "Deutsch" if code == "de" else "English",
                "params": [
                    {"name": key, "value": value}
                    for key, value in parse_qsl(parts.query, keep_blank_values=True)
                ],
                "path": parts.path or "/",
                "url": urlunsplit(
                    (parts.scheme, parts.netloc, parts.path, parts.query, parts.fragment)
                ),
            }
        )
    return links
